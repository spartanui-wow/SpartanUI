-- @runtime luals
local M, H = ...
local P
local function Env(id)
	local token = M.ShowPlate({ npcID = id, name = 'Original name', canAttack = true })
	local src = P.Source.NewLive(token)
	return { src = src, facts = { isPlayer = false }, ctx = P.Context }
end

describe('special mob colors and names', function()
	before_each(function()
		P = H.FreshCore()
		M.Login('NameplatesTestHost')
	end)
	after_each(function()
		M.SetRestricted(false)
		P:Disable()
	end)
	it('adds by id, keeps a hint, and applies only the selected NPC', function()
		local page = P.Options.ColorsPage
		assert.is_true(page.AddNPC(5925, 'Grounding Totem'))
		assert.is_true(page.SetNPC(5925, 'color', { 0.2, 0.7, 1, 1 }))
		local env = Env(5925)
		local matched, r, g, b = P.Colors:GetKind('npc').Resolve(env)
		assert.is_true(matched)
		assert.equal(r, 0.2)
		assert.equal(g, 0.7)
		assert.equal(b, 1)
		assert.is_false(P.Colors:GetKind('npc').Resolve(Env(5924)))
		assert.equal(P.Store:Get({ 'colors', 'npcs', '5925', 'hint' }), 'Grounding Totem')
		local program = P.Colors:Program('health')
		assert.equal(program.rows[1].id, 'npc')
	end)
	it('never matches restricted identity and restores the real name', function()
		local page = P.Options.ColorsPage
		page.AddNPC(5925, 'Hint')
		page.SetNPC(5925, 'rename', 'New name')
		page.SetNPC(5925, 'color', { 1, 0, 0, 1 })
		local env = Env(5925)
		assert.equal(env.src:DisplayNameSecret(), 'New name')
		M.SetRestricted(true, nil, true)
		assert.is_false(P.Colors:GetKind('npc').Resolve(env))
		assert.equal(M.S.Reveal(env.src:DisplayNameSecret()), 'Original name')
	end)
	it('clears a drawn rename at the restriction edge without waiting for a name event', function()
		P.Store:Set({ 'colors', 'npcs', '123456' }, { hint = 'Hint', rename = 'New name', color = { 1, 0, 0, 1 } })
		P:Enable()
		local token, base = M.ShowPlate({ npcID = 123456, name = 'Original name', canAttack = true })
		local plate = P.Driver:GetPlate(base)
		assert.not_nil(plate)
		local name = plate:GetWidget('name').text
		assert.equal(M.S.Reveal(M.Get(name, 'text')), 'New name')
		M.SetRestricted(true, nil, true)
		P:Fire('RESTRICTION_CHANGED', true)
		assert.equal(M.S.Reveal(M.Get(name, 'text')), 'Original name')
		M.SetRestricted(false)
		P:Fire('RESTRICTION_CHANGED', false)
		assert.equal(M.S.Reveal(M.Get(name, 'text')), 'New name')
		M.HidePlate(token)
		P:Disable()
	end)
	it('supports rename-only entries, blank resets, and removal', function()
		local page = P.Options.ColorsPage
		page.AddNPC('5925', 'Hint')
		page.SetNPC('5925', 'rename', ' New name ')
		local env = Env(5925)
		assert.equal(env.src:DisplayNameSecret(), 'New name')
		assert.is_false(P.Colors:GetKind('npc').Resolve(env))
		page.SetNPC('5925', 'rename', '')
		assert.equal(env.src:DisplayNameSecret(), 'Original name')
		assert.is_true(page.RemoveNPC('5925'))
		assert.is_nil(P.Store:Get({ 'colors', 'npcs' }))
	end)
	it('rejects invalid ids and colors', function()
		local page = P.Options.ColorsPage
		for _, id in ipairs({ 'abc', '-1', '0', '1.5', 'inf', '10000001' }) do
			assert.is_false(page.AddNPC(id))
		end
		page.AddNPC(5925, 'Hint')
		assert.is_false(page.SetNPC(5925, 'color', { -1, 0, 0, 1 }))
		assert.is_false(page.SetNPC(5925, 'color', { 0, 0, 0 }))
	end)
	it('reads the current profile for every callback', function()
		local page = P.Options.ColorsPage
		page.AddNPC(5925, 'Hint')
		page.SetNPC(5925, 'rename', 'First')
		local src = P.Source.NewSample({ npcID = 5925, name = 'Original' })
		assert.equal(src:DisplayNameSecret(), 'First')
		P.db:SetProfile('Other')
		assert.equal(src:DisplayNameSecret(), 'Original')
		page.AddNPC(5925, 'New hint')
		page.SetNPC(5925, 'rename', 'Second')
		assert.equal(src:DisplayNameSecret(), 'Second')
	end)
	it('keeps the list under More settings and only reads the target on click', function()
		local tree = P:BuildOptionsTable()
		local page = tree.args.colors.args.specialMobs
		assert.is_true(page.advanced)
		assert.matches(page.args.note.name, 'game hides')
		local token = M.ShowPlate({ npcID = 5925, name = 'Target hint' })
		M.SetTarget(token)
		page.args.target.func()
		assert.equal(P.Store:Get({ 'colors', 'npcs', '5925', 'hint' }), 'Target hint')
	end)
	it('locks writes when the game locks settings', function()
		M.EnterCombat()
		assert.is_false(P.Options.ColorsPage.AddNPC(5925, 'Hint'))
		M.LeaveCombat()
	end)
end)
