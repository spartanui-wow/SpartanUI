describe('nameplates', function()
	it('creates, adds and removes plates with the documented events', function()
		local f = CreateFrame('Frame')
		local seen = {}
		f:SetScript('OnEvent', function(_, event, arg)
			seen[#seen + 1] = event
			if event == 'NAME_PLATE_UNIT_ADDED' then
				local base = C_NamePlate.GetNamePlateForUnit(arg)
				seen.base = base
				seen.canHitTest = base:CanChangeHitTestPoints()
			end
		end)
		f:RegisterEvent('NAME_PLATE_CREATED')
		f:RegisterEvent('NAME_PLATE_UNIT_ADDED')
		f:RegisterEvent('NAME_PLATE_UNIT_REMOVED')
		-- Earlier tests left pooled base plates; hold them so this one needs a new base
		local held = {}
		for i = 1, #M.Bases() do
			held[i] = M.ShowPlate({ name = 'Holder ' .. i })
		end
		seen = {}
		local token, base = M.ShowPlate({ name = 'Murloc' })
		assert.equal(seen[1], 'NAME_PLATE_CREATED')
		assert.equal(seen[2], 'NAME_PLATE_UNIT_ADDED')
		assert.equal(seen.base, base)
		assert.is_true(seen.canHitTest)
		assert.is_false(base:CanChangeHitTestPoints(), 'only during the add event')
		assert.errors(function()
			base:SetAllHitTestPoints(UIParent)
		end, 'CanChangeHitTestPoints')
		assert.not_nil(base.UnitFrame, 'Blizzard unit frame')
		assert.equal(UnitName(token), 'Murloc')
		M.HidePlate(token)
		assert.equal(seen[3], 'NAME_PLATE_UNIT_REMOVED')
		assert.is_nil(C_NamePlate.GetNamePlateForUnit(token))
		local token2, base2 = M.ShowPlate({ name = 'Reused' })
		assert.equal(base2, base, 'base plates are pooled')
		M.HidePlate(token2)
		for _, heldToken in ipairs(held) do
			M.HidePlate(heldToken)
		end
	end)
	it('keeps forbidden plates away from addons', function()
		local token = M.ShowPlate({ name = 'Friend', forbidden = true, reaction = 5 })
		assert.is_nil(C_NamePlate.GetNamePlateForUnit(token))
		M.HidePlate(token)
	end)
	it('swaps target, focus and mouseover tokens', function()
		local token = M.ShowPlate({ name = 'Target Dummy' })
		M.SetTarget(token)
		assert.is_true(UnitIsUnit('target', token))
		assert.equal(C_NamePlate.GetNamePlateForUnit('target'), M.plates[token])
		M.SetTarget(nil)
		assert.is_false(UnitExists('target'))
		M.HidePlate(token)
	end)
	it('models casts, threat and auras', function()
		local token, _, unit = M.ShowPlate({ name = 'Caster', classification = 'elite' })
		M.StartCast(unit, { name = 'Fireball', spellID = 133, duration = 2 })
		local name, _, _, startMS, endMS, _, _, notInterruptible, spellID = UnitCastingInfo(token)
		assert.equal(name, 'Fireball')
		assert.equal(endMS - startMS, 2000)
		assert.is_false(notInterruptible)
		assert.equal(spellID, 133)
		M.StopCast(unit, 'interrupted')
		assert.is_nil(UnitCastingInfo(token))
		M.SetThreat(unit, M.player, { status = 3, scaledPercent = 100 })
		assert.equal(UnitThreatSituation('player', token), 3)
		M.ApplyAura(unit, { spellId = 589, isHarmful = true, sourceUnit = 'player', duration = 18 })
		local aura = C_UnitAuras.GetAuraDataByIndex(token, 1, 'HARMFUL|PLAYER')
		assert.equal(aura and aura.spellId, 589)
		assert.is_nil(C_UnitAuras.GetAuraDataByIndex(token, 1, 'HELPFUL'))
		M.HidePlate(token)
	end)
end)

