describe('secret values', function()
	it('raise on every operator but concatenation', function()
		local n = S.Wrap(5)
		assert.errors(function()
			return n + 1
		end, 'arithmetic')
		assert.errors(function()
			return n < 1
		end)
		assert.errors(function()
			return n <= 1
		end)
		assert.errors(function()
			return n == S.Wrap(5)
		end, 'compare')
		assert.errors(function()
			return #S.Wrap('text')
		end, 'length')
		assert.errors(function()
			return S.Wrap('text'):upper()
		end, 'index')
		assert.errors(function()
			S.Wrap(1)()
		end, 'call')
		assert.secret('Health: ' .. n)
		assert.secret(tostring(n))
		assert.secret(string.format('%d', n))
		assert.equal(type(n), 'number')
		assert.equal(type(S.Wrap(true)), 'boolean')
		assert.equal(S.Reveal('Health: ' .. n), 'Health: 5')
	end)
	it('are seen through by the documented helpers', function()
		if not canaccessvalue then
			skip('this client does not document canaccessvalue')
		end
		assert.is_false(canaccessvalue(S.Wrap(1)))
		assert.is_true(canaccessvalue(1))
		assert.is_true(issecretvalue(S.Wrap(1)))
	end)
	it('are refused by setters that only take them from Blizzard code', function()
		if not M.secrets then
			skip('no secrets on this client')
		end
		local f = CreateFrame('Frame')
		local bar = CreateFrame('StatusBar')
		assert.errors(function()
			f:SetWidth(S.Wrap(10))
		end, 'secret')
		assert.no_errors(function()
			bar:SetValue(S.Wrap(10))
			bar:SetMinMaxValues(0, S.Wrap(100))
		end)
		assert.secret(bar:GetValue())
		f:SetAlphaFromBoolean(S.Wrap(false), 1, 0)
		assert.equal(M.Get(f, 'alpha'), 0)
		assert.errors(function()
			f:SetAlphaFromBoolean(S.Wrap(true))
		end, 'explicitly')
	end)
	it('fold through the color chain', function()
		if not (C_CurveUtil and C_CurveUtil.EvaluateColorValueFromBoolean) then
			skip('no color curve API')
		end
		local r = C_CurveUtil.EvaluateColorValueFromBoolean(S.Wrap(true), 1, 0.5)
		r = C_CurveUtil.EvaluateColorValueFromBoolean(S.Wrap(false), 0.2, r)
		assert.secret(r)
		assert.equal(S.Reveal(r), 1)
	end)
end)

