		local entries = H.ParseLoadXml(FAKE .. 'Load.xml')
		local scripts, templates = {}, {}
		for _, e in ipairs(entries) do
			if e.kind == 'script' then
				scripts[#scripts + 1] = e.path:match('[^/]+$')
			elseif e.kind == 'template' then
				templates[#templates + 1] = e.name
			end
		end
		assert.same(scripts, { 'First.lua', 'Second.lua', 'Last.lua' })
		assert.same(templates, { 'FakeModuleCardTemplate' })
	end)
	it('loads a core and a host against the SUI mock', function()
		local ns = H.LoadCore({ xml = FAKE .. 'Load.xml' })
		assert.same(ns.order, { 'First', 'Second', 'Last' })
