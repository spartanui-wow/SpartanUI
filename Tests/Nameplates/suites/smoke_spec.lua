		assert.not_nil(ns.card, 'addon-defined templates can be used')
		local SUI = H.LoadSpartanUIHost({ ns = ns, file = FAKE .. 'Host/SpartanUI.lua' })
		assert.is_true(ns.hostFoundModule, 'the old Nameplates module exists for the host')
		assert.equal(SUI:GetModule('Nameplates').API, ns)
		assert.equal(H.sui.options[1].parent, 'Root')
		assert.not_nil(H.logs.Nameplates)
		assert.equal(SUI.IsForever, M.flavor == 'forever')
	end)
