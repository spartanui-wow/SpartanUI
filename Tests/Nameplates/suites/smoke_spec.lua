describe('time', function()
	it('runs timers, tickers and OnUpdate', function()
		local after, ticks, updates = 0, 0, 0
		C_Timer.After(1, function()
			after = after + 1
		end)
		local ticker = C_Timer.NewTicker(0.5, function()
			ticks = ticks + 1
		end)
		local f = CreateFrame('Frame')
		f:SetScript('OnUpdate', function()
			updates = updates + 1
		end)
		M.Advance(2)
		assert.equal(after, 1)
		assert.truthy(ticks >= 3, 'ticker ran')
		assert.truthy(updates > 10, 'OnUpdate ran')
		ticker:Cancel()
		f:Hide()
		local frozen = updates
		M.Advance(1)
		assert.equal(updates, frozen, 'hidden frames do not update')
		assert.truthy(#M.rec.tickers >= 1)
	end)
end)

describe('hooks', function()
	it('runs a post-hook and keeps the original result', function()
		local t = {}
		function t.Add(a, b)
			return a + b
		end
		local seen
		hooksecurefunc(t, 'Add', function(a, b)
			seen = a * b
		end)
		assert.equal(t.Add(2, 3), 5)
		assert.equal(seen, 6)
		assert.equal(M.rec.hooks[#M.rec.hooks].name, 'Add')
		assert.errors(function()
			hooksecurefunc(t, 'Missing', function() end)
		end, 'not a function')
	end)
	it('can hook the nameplate driver and the CVar setter', function()
		assert.not_nil(NamePlateDriverFrame, 'NamePlateDriverFrame')
		local calls = 0
		hooksecurefunc(NamePlateDriverFrame, 'UpdateNamePlateOptions', function()
			calls = calls + 1
		end)
		NamePlateDriverFrame:UpdateNamePlateOptions()
		assert.equal(calls, 1)
		local writes = 0
		hooksecurefunc(C_CVar, 'SetCVar', function()
			writes = writes + 1
		end)
		SetCVar('nameplateShowEnemies', '1')
		assert.equal(writes, 1, 'the global SetCVar goes through C_CVar.SetCVar')
	end)
end)

